package ru.practicum.shareit.booking.dto;

/**
 * Какие брони показать в списке. Gateway проверяет, что в параметре state одно из этих значений,
 * и передаёт его серверу как есть. Неизвестное значение — ошибка 400 ещё до сервера.
 */
public enum BookingState {
    ALL,      // все
    CURRENT,  // идут сейчас
    PAST,     // уже закончились
    FUTURE,   // ещё не начались
    WAITING,  // ждут решения владельца
    REJECTED  // отклонены владельцем
}
